import json
import os
import shutil
import tarfile
from unittest.mock import patch

import pytest

from test_game_sync import h
from test_pack_exclusions import packer


MUTABLE = ('cache/longshot_prepared.bin', 'cache/longshot_programs.bin', 'cache/longshot_programs.idx')
SHIPPED = ('longshot.exe', 'longshot_version.txt', 'longshot_shaders.bin', 'cache/longshot_pipelines.bin',
           'cache/longshot_vk_pipelines.bin', 'cache/longshot_vk_pipelines.stamp', 'cache/longshot_prepare_results.txt',
           'cache/prompts/intro.bin', 'nested/cache/longshot_programs.bin')


@pytest.fixture
def release(tmp_path):
    source = tmp_path / 'payload'
    for name in MUTABLE + SHIPPED:
        path = source / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(name.encode())
    out = tmp_path / 'release'
    return out, packer.pack(source, out)


def test_only_working_caches_omitted_from_manifest_and_bundles(release):
    out, manifest = release
    assert sorted(entry['path'] for entry in manifest['files']) == sorted(SHIPPED)
    members = []
    for path in out.iterdir():
        with tarfile.open(path) as bundle:
            members.extend(bundle.getnames())
    assert sorted(members) == sorted(SHIPPED)


@pytest.mark.skipif(os.name != 'nt', reason='Windows native file checks')
def test_post_play_reverify_keeps_native_plan(release, tmp_path, monkeypatch):
    out, manifest = release
    manifest = h.parse_game_manifest(json.dumps(manifest))
    root = tmp_path / 'install'
    shutil.copytree(out, root / '.heylisten-parts')  # Supply the release bundle offline.
    monkeypatch.setattr(h, 'LOG_PATH', tmp_path / 'install.log')
    monkeypatch.setenv('SILVER_LANTERN_TEST_NO_DEFENDER', '1')
    h.install_game(None, manifest, root)
    for name in MUTABLE:
        assert not (root / name).exists()
        (root / name).write_bytes(b'generated by play')

    with patch.object(h, 'destination_inventory', side_effect=AssertionError('abandoned native plan')):
        h.install_game(None, manifest, root, dry_run=True)
    assert f'Plan: {len(SHIPPED)} files present, 0 to download' in h.LOG_PATH.read_text(encoding='utf-8')
